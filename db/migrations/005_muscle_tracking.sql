-- Mapa de musculos trabajados por ejercicio.
CREATE TABLE IF NOT EXISTS exercise_muscle_map (
  id              INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  exercise_name   VARCHAR(100) NOT NULL,
  muscle_group    ENUM(
    'pecho','espalda','hombros','biceps','triceps',
    'cuadriceps','femorales','gluteos','pantorrillas',
    'abdomen','antebrazos','aductores','abductores'
  ) NOT NULL,
  activation_pct  TINYINT UNSIGNED NOT NULL DEFAULT 100,
  is_primary      BOOLEAN NOT NULL DEFAULT TRUE,
  UNIQUE KEY uq_exercise_muscle (exercise_name, muscle_group),
  INDEX idx_exercise (exercise_name),
  INDEX idx_muscle (muscle_group)
);

-- Volumen muscular acumulado por sesion.
CREATE TABLE IF NOT EXISTS session_muscle_volume (
  id              BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id         INT UNSIGNED NOT NULL,
  session_date    DATE NOT NULL,
  muscle_group    ENUM(
    'pecho','espalda','hombros','biceps','triceps',
    'cuadriceps','femorales','gluteos','pantorrillas',
    'abdomen','antebrazos','aductores','abductores'
  ) NOT NULL,
  total_sets      SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  total_reps      INT UNSIGNED NOT NULL DEFAULT 0,
  total_volume_kg DECIMAL(10,2) NOT NULL DEFAULT 0,
  intensity_score TINYINT UNSIGNED NOT NULL DEFAULT 0,
  created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_user_session_muscle (user_id, session_date, muscle_group),
  INDEX idx_user_date (user_id, session_date),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

